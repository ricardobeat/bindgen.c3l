// Returns the embedded text of a chibicc-provided header, or NULL.
char *builtin_header(char *name) {
  for (int i = 0; builtin_headers[i].name; i++)
    if (!strcmp(builtin_headers[i].name, name))
      return builtin_headers[i].body;
  return NULL;
}
